const assert = require("node:assert/strict");
const fs = require("node:fs");
const Module = require("node:module");
const { transformSync } = require("esbuild");
const path = require("node:path");
const filename = path.resolve(__dirname, "../src/components/admin/accountControlSearch.ts");
const loaded = new Module(filename, module);
loaded._compile(transformSync(fs.readFileSync(filename, "utf8"), { loader: "ts", format: "cjs" }).code, filename);
const { accountControls, findAccountControls } = loaded.exports;
const ids = query => findAccountControls(query).map(control => control.id);
assert.equal(new Set(accountControls.map(control => control.id)).size, accountControls.length);
assert.equal(ids("")[0], "refund");
assert.equal(ids("return money")[0], "refund");
assert.equal(ids("refnd")[0], "refund");
assert(ids("how do i refund this rental").includes("refund"));
assert(ids("reimburse").includes("refund"));
assert(ids("extend").includes("manage-rental"));
assert(ids("blacklist").includes("restriction"));
assert(ids("subscrption").includes("membership"));
assert.deepEqual(ids("pterodactyl"), []);
const accountSource = fs.readFileSync(path.resolve(__dirname, "../src/components/admin/AccountAdmin.tsx"), "utf8");
const adminSource = fs.readFileSync(path.resolve(__dirname, "../src/app/admin/page.tsx"), "utf8");
const renterSource = fs.readFileSync(path.resolve(__dirname, "../src/components/RenterChat.tsx"), "utf8");
assert.match(adminSource, /if \(!token \|\| authed === false\)/);
assert.match(adminSource, /if \(authed !== true\)/);
assert.match(adminSource, /<AccountAdmin token=\{token\}/);
assert.doesNotMatch(renterSource, /AccountAdmin|admin-control-search/);
assert.match(accountSource, /button\.disabled\) return/);
assert.match(accountSource, /selected\.id !== controlIntent\.accountId/);
assert.match(accountSource, /managedRental\?\.id !== controlIntent\.bookingId/);
console.log("Admin control search: synonym, typo, scope and guarded-action checks passed.");
