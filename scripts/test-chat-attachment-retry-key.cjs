const assert = require("node:assert/strict");
const { load } = require("./lib/rentalTestHarness.cjs");
const { attachmentRetryKey, clearAttachmentRetryKey } = load("src/lib/chatAttachmentRetry.ts");
const rows = new Map();
const storage = { getItem: key => rows.get(key) ?? null, setItem: (key, value) => rows.set(key, value), removeItem: key => rows.delete(key) };
let counter = 0;
const create = () => String(++counter).padStart(32, "0");
const first = attachmentRetryKey(storage, "scope-a", "a".repeat(64), false, create);
assert.equal(attachmentRetryKey(storage, "scope-a", "a".repeat(64), false, create), first, "same-tab reload finds the original pending key");
assert.notEqual(attachmentRetryKey(storage, "scope-a", "b".repeat(64), false, create), first, "different source bytes never reuse the key");
assert.notEqual(attachmentRetryKey(storage, "scope-b", "a".repeat(64), false, create), first, "another account or conversation never shares the key");
assert.notEqual(attachmentRetryKey(storage, "scope-a", "a".repeat(64), true, create), first, "clean-copy mode is separate");
clearAttachmentRetryKey(storage, "scope-a", "a".repeat(64), false, "different-key-0000");
assert.equal(attachmentRetryKey(storage, "scope-a", "a".repeat(64), false, create), first, "stale success cannot clear another attempt");
clearAttachmentRetryKey(storage, "scope-a", "a".repeat(64), false, first);
assert.notEqual(attachmentRetryKey(storage, "scope-a", "a".repeat(64), false, create), first, "success permits a deliberate new send");
const unavailable = { getItem() { throw Error("blocked"); }, setItem() { throw Error("blocked"); }, removeItem() { throw Error("blocked"); } };
assert.match(attachmentRetryKey(unavailable, "scope-a", "c".repeat(64), false, create), /^[0-9]{32}$/);
clearAttachmentRetryKey(unavailable, "scope-a", "c".repeat(64), false, "00000000000000000000000000000000");
console.log("PASS tab-scoped attachment retry keys: reload, scope and file separation, cleanup, and unavailable storage.");
