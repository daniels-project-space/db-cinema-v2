assert.equal(p.lensUpgrade({...lens,title:'2x Sony 24-70mm GM'},[body,standard]),null);
assert.equal(p.lensUpgrade({...lens,components:[{inventoryUnitId:'gm',qty:2}]},[body,standard]),null);
