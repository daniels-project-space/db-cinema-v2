const assert = require('node:assert/strict');
const {load, db, put} = require('./lib/rentalTestHarness.cjs');
const {requiresDroneLicence, assertDroneApproval} = load('convex/lib/droneVerification.ts');
const licences = load('convex/droneLicences.ts');
process.env.ADMIN_TOKEN = 'fixture-admin';
const drone = put('listings', {itemType:'drone', components:[]});
const camera = put('listings', {itemType:'camera-body', components:[]});
const unit = put('inventory_units', {name:'DJI Mavic 3 Cine'});
const bundle = put('listings', {itemType:'bundle', components:[{inventoryUnitId:unit._id,qty:1}]});
const account = put('accounts', {email:'renter@example.invalid'});
put('sessions', {token:'owner',accountId:account._id,expiresAt:Date.now()+60000});
const other = put('accounts', {email:'other@example.invalid'});
put('sessions', {token:'other',accountId:other._id,expiresAt:Date.now()+60000});
const booking = put('bookings', {accountId:account._id,status:'confirmed',depositHoldAmount:0,lineItems:[{listingId:drone._id}],stripeCheckoutSessionId:'cs_fixture'});
const ctx={db,storage:{generateUploadUrl:async()=> 'https://upload.invalid',getUrl:async()=> 'https://private.invalid'}};
db.system={get:async id => id==='valid-file'?{size:512,contentType:'application/pdf'}:{size:512,contentType:'text/html'}};
(async()=>{
 assert.equal(await requiresDroneLicence(ctx,{lineItems:[{listingId:camera._id}]}),false);
 assert.equal(await requiresDroneLicence(ctx,{lineItems:[{listingId:bundle._id}]}),true);
 await assert.rejects(()=>assertDroneApproval(ctx,booking),/approved/);
 await assert.rejects(()=>licences.uploadUrl.handler(ctx,{bookingId:booking._id,token:'other'}),/account/);
 await assert.rejects(()=>licences.submit.handler(ctx,{bookingId:booking._id,token:'owner',storageId:'html'}),/PDF/);
 await licences.submit.handler(ctx,{bookingId:booking._id,token:'owner',storageId:'valid-file'});
 assert.equal(booking.droneLicenceStatus,'review');
 await assert.rejects(()=>assertDroneApproval(ctx,booking),/approved/);
 await assert.rejects(()=>licences.review.handler(ctx,{token:'fixture-admin',bookingId:booking._id,decision:'approved',note:'ok'}),/Record/);
 await licences.review.handler(ctx,{token:'fixture-admin',bookingId:booking._id,decision:'approved',note:'Operator details and evidence assessed.'});
 await assertDroneApproval(ctx,booking);
 await assert.rejects(()=>licences.submit.handler(ctx,{bookingId:booking._id,token:'owner',storageId:'valid-file'}),/already approved/);
 await licences.review.handler(ctx,{token:'fixture-admin',bookingId:booking._id,decision:'requires_input',note:'Please upload the current operator evidence.'});
 await assert.rejects(()=>assertDroneApproval(ctx,booking),/approved/);
 booking.status='returned';
 await assert.rejects(()=>licences.uploadUrl.handler(ctx,{bookingId:booking._id,token:'owner'}),/before collection/);
 console.log('PASS drone detection including bundles, ownership, content validation, manual review, decision notes, reopening and closed-rental protection.');
})().catch(e=>{console.error(e);process.exitCode=1});
