const assert = require('node:assert/strict');
const { load, db, put, tables } = require('./lib/rentalTestHarness.cjs');
const invitations = load('convex/reviewInvitations.ts');
const { reviewContext } = load('convex/lib/reviewContext.ts');
const { reviewSettlementFingerprint } = load('convex/lib/reviewEligibility.ts');
const original = process.env.ADMIN_TOKEN;
process.env.ADMIN_TOKEN = 'review-admin-test';
const account = put('accounts', { email: 'renter@example.invalid', name: 'Renter' });
put('sessions', { token: 'renter-session', accountId: account._id, expiresAt: Date.now() + 60_000 });
const booking = put('bookings', { accountId: account._id, guestEmail: account.email, status: 'returned', depositAmount: 0, total: 40, lineItems: [] });
const ctx = { db };
const args = { token: 'review-admin-test', bookingId: booking._id };
(async () => {
  assert.equal(await invitations.adminStatus.handler(ctx, { ...args, token: 'wrong' }), null);
  await assert.rejects(invitations.sendByAdmin.handler(ctx, { ...args, token: 'wrong' }), /unauthorized/);
  assert.equal((await invitations.adminStatus.handler(ctx, args)).state, 'check_required');
  await assert.rejects(invitations.sendByAdmin.handler(ctx, args), /settlement/);
  assert.equal((tables.get('messages') ?? []).length, 0);
  await db.patch(booking._id, { reviewFollowUpDueAt: Date.now() - 1 });
  await db.patch(booking._id, { reviewEligibilityFingerprint: reviewSettlementFingerprint(await reviewContext(ctx, await db.get(booking._id))) });
  assert.equal((await invitations.adminStatus.handler(ctx, args)).state, 'ready');
  await db.patch(booking._id, { depositHoldAmount: 50 });
  assert.equal((await invitations.adminStatus.handler(ctx, args)).state, 'not_settled', 'An untraceable newly recorded hold cannot reuse an older settlement approval');
  await assert.rejects(invitations.sendByAdmin.handler(ctx, args), /settlement/);
  assert.equal((await invitations.eligibility.handler(ctx, { token: 'renter-session', bookingId: booking._id })).eligible, false);
  await db.patch(booking._id, { depositHoldAmount: 0 });
  await db.patch(booking._id, { lateFeeAmount: 5, lateFeeStatus: 'pending' });
  assert.equal((await invitations.adminStatus.handler(ctx, args)).state, 'not_settled');
  await assert.rejects(invitations.sendByAdmin.handler(ctx, args), /settlement/);
  await db.patch(booking._id, { lateFeeAmount: undefined, lateFeeStatus: undefined });
  await db.patch(booking._id, { status: 'active' });
  await assert.rejects(invitations.sendByAdmin.handler(ctx, args), /settlement/);
  await db.patch(booking._id, { status: 'returned' });
  assert.equal((await invitations.sendByAdmin.handler(ctx, args)).state, 'sent');
  assert.equal((await invitations.sendByAdmin.handler(ctx, args)).state, 'sent');
  assert.equal(tables.get('messages').length, 1, 'retries never send a duplicate invitation');
  assert.equal(tables.get('messages')[0].meta.kind, 'review_invitation');
  assert.match(tables.get('messages')[0].text, /https:\/\/dbcinemarentals\.com\/account\?rental=/, 'The invitation keeps a usable review link');
  assert.equal((await invitations.adminStatus.handler(ctx, args)).state, 'sent');
  await db.patch(tables.get('messages')[0]._id, { at: Date.now() - 25 * 60 * 60 * 1000 });
  assert.equal((await invitations.adminStatus.handler(ctx, args)).state, 'resend_ready');
  assert.equal((await invitations.sendByAdmin.handler(ctx, args)).state, 'sent');
  assert.equal((await invitations.sendByAdmin.handler(ctx, args)).state, 'sent');
  assert.equal(tables.get('messages').length, 2, 'explicit reminder is rate-limited and idempotent');
  put('reviews', { verifiedBookingId: booking._id, source: 'native', rating: 4 });
  assert.equal((await invitations.adminStatus.handler(ctx, args)).state, 'reviewed');
  assert.equal((await invitations.sendByAdmin.handler(ctx, args)).state, 'reviewed');
  assert.equal(tables.get('messages').length, 2, 'completed reviews prevent new requests');
  const emailSent = put('bookings', { accountId: account._id, guestEmail: account.email, status: 'returned', depositAmount: 0, total: 40, lineItems: [], reviewFollowUpStatus: 'sent', remindedReview: true });
  const emailArgs = { token: 'review-admin-test', bookingId: emailSent._id };
  assert.equal((await invitations.adminStatus.handler(ctx, emailArgs)).state, 'sent', 'A sent email closes the admin chat invitation too');
  assert.equal((await invitations.sendByAdmin.handler(ctx, emailArgs)).state, 'sent');
  const emailSending = put('bookings', { accountId: account._id, guestEmail: account.email, status: 'returned', depositAmount: 0, total: 40, lineItems: [], reviewFollowUpStatus: 'sending' });
  const sendingArgs = { token: 'review-admin-test', bookingId: emailSending._id };
  assert.equal((await invitations.adminStatus.handler(ctx, sendingArgs)).state, 'sending', 'An in-flight email closes the admin chat invitation');
  assert.equal((await invitations.sendByAdmin.handler(ctx, sendingArgs)).state, 'sending');
  assert.equal(tables.get('messages').length, 2, 'Email sent/in-flight state cannot create another invitation in chat');
  console.log('PASS admin review request: authorization, settlement gate, changed state, native chat and duplicate prevention');
})().catch(error => { console.error(error); process.exitCode = 1; }).finally(() => { if (original === undefined) delete process.env.ADMIN_TOKEN; else process.env.ADMIN_TOKEN = original; });
