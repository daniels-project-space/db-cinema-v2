const assert = require("node:assert/strict");
const { createHash } = require("node:crypto");
const { load, db, tables, setMock } = require("./lib/rentalTestHarness.cjs");
const routes = [];
setMock("convex/server", { ...require("convex/server"), httpRouter: () => ({ route: route => routes.push(route) }) });
load("convex/http.ts");
const claims = load("convex/accountCodeClaims.ts");
const endpoint = routes.find(route => route.path === "/signup-avatar" && route.method === "POST").handler;
const hash = value => createHash("sha256").update(value).digest("hex");
const files = new Map();
db.system.get = async id => files.has(id) ? { _id: id } : null;
const scheduled = [];
let serial = 0, failUpload = false, failDelete = false;
const storage = { store: async blob => { if (failUpload) throw Error("storage failed"); const id = `photo-${++serial}`; files.set(id, blob); return id; }, get: async id => files.get(id) ?? null, delete: async id => { if (failDelete) throw Error("temporary storage failure"); files.delete(id); } };
const inner = { db, storage, scheduler: { runAt: async (...args) => scheduled.push(args), runAfter: async (...args) => scheduled.push(args) } };
const context = { storage, runQuery: async (ref, args) => claims[String(ref).split(".").pop()].handler(inner, args), runMutation: async (ref, args) => claims[String(ref).split(".").pop()].handler(inner, args) };
const photo = Buffer.from([0xff, 0xd8, 0xff, 0x01]);
const request = (token, preview = false, body = photo) => new Request(`https://fixture.convex.site/signup-avatar${preview ? "?preview=1" : ""}`, { method: "POST", headers: { Origin: "https://dbcinemarentals.com", Authorization: `Bearer ${token}`, ...(preview ? {} : { "Content-Type": "image/jpeg" }) }, ...(preview ? {} : { body }) });
const setup = async (label, token) => claims.prepare.handler(inner, { email: `${label}@example.invalid`, name: "Test renter", phone: "07700900000", purpose: "setup", challengeHash: hash(token), codeHash: hash("code") });
const finish = token => ({ setupHash: hash(token), salt: "salt", hash: "password", sessionToken: `session-${token}`, termsAndPrivacyAcknowledged: true, termsVersion: "fixture", privacyNoticeVersion: "fixture" });

(async () => {
  const challenge = "a".repeat(43), proof = "b".repeat(43);
  await setup("photo-owner", challenge);
  assert.equal((await endpoint(context, request(challenge, true))).status, 404, "a signup challenge cannot view the staged photo");
  assert.equal((await endpoint(context, request(challenge))).status, 200);
  const row = tables.get("account_codes")[0], photoId = row.pendingAvatarId;
  assert(files.has(photoId));
  assert.equal((await db.query("accounts").collect()).length, 0, "upload alone never creates an account");
  assert.equal((await endpoint(context, request("z".repeat(43), true))).status, 404, "another setup token cannot read it");
  assert.equal((await claims.verify.handler(inner, { challengeHash: hash(challenge), codeHash: hash("code"), setupHash: hash(proof) })).ok, true);
  assert.equal((await endpoint(context, request(proof, true))).status, 200, "the email-verified owner can preview the photo in another tab or device");
  assert.equal((await endpoint(context, request(challenge))).status, 200, "a photo upload racing with verification remains a generic response");
  assert.equal(row.pendingAvatarId, photoId, "a challenge cannot replace the image after the owner verifies it");
  await claims.finish.handler(inner, { ...finish(proof), acceptPendingAvatar: true });
  const account = (await db.query("accounts").collect())[0];
  assert.equal(account.avatarStorageId, photoId);
  assert.equal(account.avatarOwnedStorageId, photoId);
  assert.equal(row.pendingAvatarId, undefined);
  assert.equal((await endpoint(context, request(proof, true))).status, 404, "the setup preview cannot be replayed after completion");
  await claims.expirePendingAvatar.handler(inner, scheduled[0][2]);
  assert(files.has(photoId), "expiry cannot delete an accepted profile image");

  const rejectedChallenge = "c".repeat(43), rejectedProof = "d".repeat(43);
  await setup("photo-decline", rejectedChallenge);
  await endpoint(context, request(rejectedChallenge));
  const rejectedRow = tables.get("account_codes").at(-1), rejectedId = rejectedRow.pendingAvatarId;
  await claims.verify.handler(inner, { challengeHash: hash(rejectedChallenge), codeHash: hash("code"), setupHash: hash(rejectedProof) });
  await claims.finish.handler(inner, finish(rejectedProof));
  assert(!files.has(rejectedId), "an unaccepted photo is deleted when setup finishes");
  assert.equal((await db.query("accounts").withIndex("by_email", q => q.eq("email", "photo-decline@example.invalid")).first()).avatarStorageId, undefined);

  const expiredChallenge = "e".repeat(43);
  await setup("photo-expiry", expiredChallenge);
  await endpoint(context, request(expiredChallenge));
  const expiredRow = tables.get("account_codes").at(-1), expiredId = expiredRow.pendingAvatarId;
  await db.patch(expiredRow._id, { expiresAt: Date.now() - 1 });
  failDelete = true;
  await claims.expirePendingAvatar.handler(inner, { codeId: expiredRow._id, storageId: expiredId });
  assert.equal(scheduled.at(-1)[2].attempt, 1, "a transient cleanup failure schedules a bounded retry");
  assert.equal(expiredRow.pendingAvatarId, expiredId, "cleanup failure retains the reference for retry");
  failDelete = false;
  await claims.expirePendingAvatar.handler(inner, { codeId: expiredRow._id, storageId: expiredId });
  assert(!files.has(expiredId), "unused photos are removed when the challenge expires");
  assert.equal((await endpoint(context, request(expiredChallenge))).status, 200, "an expired challenge receives the same generic response");
  assert.equal(expiredRow.pendingAvatarId, undefined, "an expired challenge cannot stage a new photo");
  assert.equal((await endpoint(context, request("z".repeat(43)))).status, 200, "an unknown challenge does not reveal whether an account exists");

  const raceChallenge = "g".repeat(43), raceProof = "h".repeat(43);
  await setup("photo-race", raceChallenge);
  assert.equal(await claims.reserveAvatar.handler(inner, { challengeHash: hash(raceChallenge), leaseKey: "first" }), true);
  assert.equal(await claims.reserveAvatar.handler(inner, { challengeHash: hash(raceChallenge), leaseKey: "second" }), false, "parallel uploads cannot both consume an image body");
  await claims.verify.handler(inner, { challengeHash: hash(raceChallenge), codeHash: hash("code"), setupHash: hash(raceProof) });
  const beforeRace = files.size;
  await claims.stageAvatar.handler(inner, { challengeHash: hash(raceChallenge), leaseKey: "first", contentType: "image/jpeg", chunks: [Uint8Array.from(photo).buffer] });
  assert.equal(files.size, beforeRace, "verification between eligibility and commit prevents late staging");
  assert.equal(await claims.pendingAvatar.handler(inner, { setupHash: hash(raceProof) }), null);

  const failedChallenge = "f".repeat(43);
  await setup("photo-failure", failedChallenge);
  assert.equal((await endpoint(context, request(failedChallenge, false, Buffer.from("not a photo")))).status, 400, "file signatures are checked before staging");
  assert.equal(tables.get("account_codes").at(-1).pendingAvatarId, undefined);
  failUpload = true;
  assert.equal((await endpoint(context, request(failedChallenge))).status, 400, "upload failures are reported");
  assert.equal(tables.get("account_codes").at(-1).pendingAvatarId, undefined);
  failUpload = false;
  console.log("PASS signup photo: private challenge staging, verified-owner preview and consent, expiry, failure and replay.");
})().catch(error => { console.error(error); process.exitCode = 1; });
