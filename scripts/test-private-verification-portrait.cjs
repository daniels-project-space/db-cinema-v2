const assert = require("node:assert/strict");
const { load, db, put, setMock } = require("./lib/rentalTestHarness.cjs");
let ready = true, viewable = true, available = true, reads = 0;
setMock("./lib/accountVerificationReady", { accountVerificationReady: async () => ready });
setMock("./verificationArchive", { archiveRetention: async () => ({ viewable }), documentCopyAvailable: async () => available });
const portrait = load("convex/privateVerificationPortrait.ts");
process.env.ADMIN_TOKEN = "fixture-admin";
const now = Date.now();
const account = put("accounts", { email: "fixture@example.invalid", createdAt: now - 25 * 3600000 });
const booking = put("bookings", { accountId: account._id, diditSessionId: "session" });
account.rentalVerification = { sourceBookingId: booking._id };
const archive = put("verification_archives", { accountId: account._id, bookingId: booking._id, sessionId: "session", status: "complete" });
const document = put("verification_documents", { accountId: account._id, bookingId: booking._id, archiveId: archive._id, sessionId: "session", kind: "selfie-0-reference_image", contentType: "image/jpeg" });
const ctx = { db: { ...db, get: async id => { reads++; return db.get(id); } } };
const args = { token: "fixture-admin", accountId: account._id, refresh: 0 };

(async () => {
 delete process.env.PRIVATE_VERIFICATION_PHOTO_ENABLED;
 assert.equal(await portrait.availability.handler(ctx, { token: "fixture-admin" }), false);
 assert.equal(await portrait.selected.handler(ctx, args), null, "Feature stays disabled without notice rollout");
 process.env.PRIVATE_VERIFICATION_PHOTO_ENABLED = "true";
 assert.equal(await portrait.availability.handler(ctx, { token: "wrong" }), false);
 assert.equal(await portrait.availability.handler(ctx, { token: "fixture-admin" }), true);
 assert.equal(await portrait.selected.handler(ctx, { ...args, token: "wrong" }), null);
 assert.equal(reads, 0, "Unauthorised requests read no customer data");
 assert.equal(await portrait.selected.handler(ctx, args), null, "Account creation time is not evidence of notice");
 account.privateVerificationPortraitNoticeVersion = "2026-11-06";
 account.privateVerificationPortraitNotifiedAt = now - 24 * 3600000;
 assert.equal(await portrait.selected.handler(ctx, args), null, "Notice alone is not consent");
 account.privateVerificationPortraitConsentVersion = "2026-11-06";
 account.privateVerificationPortraitConsentedAt = now - 24 * 3600000;
 assert.deepEqual(await portrait.selected.handler(ctx, args), { documentId: document._id });
 put("sessions", { accountId: account._id, token: "renter", expiresAt: now + 60000 });
 await portrait.setPreference.handler(ctx, { token: "renter", allowed: false, noticeVersion: "2026-11-06", expectedRevision: 0 });
 assert.equal(await portrait.selected.handler(ctx, args), null, "Withdrawal immediately disables private selection");
 account.privateVerificationPortraitNoticeVersion = "2026-11-06";
 account.privateVerificationPortraitNotifiedAt = now - 24 * 3600000;
 account.privateVerificationPortraitConsentVersion = "2026-11-06";
 account.privateVerificationPortraitConsentedAt = now - 24 * 3600000;
 account.createdAt = now - 23 * 3600000;
 assert.equal(await portrait.selected.handler(ctx, args), null, "At least 24 hours must pass");
 account.createdAt = now - 25 * 3600000;
 account.avatarStorageId = "uploaded"; assert.equal(await portrait.selected.handler(ctx, args), null); account.avatarStorageId = undefined;
 account.googleAvatarUrl = "https://example.invalid/avatar"; assert.equal(await portrait.selected.handler(ctx, args), null); account.googleAvatarUrl = undefined;
 ready = false; assert.equal(await portrait.selected.handler(ctx, args), null); ready = true;
 viewable = false; assert.equal(await portrait.selected.handler(ctx, args), null); viewable = true;
 available = false; assert.equal(await portrait.selected.handler(ctx, args), null); available = true;
 archive.status = "deleted"; assert.equal(await portrait.selected.handler(ctx, args), null); archive.status = "complete";
 document.kind = "face-match-0-target_image"; assert.equal(await portrait.selected.handler(ctx, args), null); document.kind = "selfie-0-reference_image";
 archive.accountId = "other"; assert.equal(await portrait.selected.handler(ctx, args), null); archive.accountId = account._id;
 booking.accountId = "other"; assert.equal(await portrait.selected.handler(ctx, args), null);
 console.log("PASS private verification portrait: explicit rollout, 24 hours, ownership, approved archive, retention and existing-photo checks");
})().catch(error => { console.error(error); process.exitCode = 1; });
