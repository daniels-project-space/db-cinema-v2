add({type:'view',at:now-60000,path:'/first',sessionId:'same'},1);
add({type:'view',at:now-120000,path:'/second',sessionId:'same'},2);
add({type:'view',at:now+60000,path:'/future',sessionId:'future'},3);
add({type:'view',at:now-7*DAY,path:'/boundary'},4);
add({type:'search_no_results',at:now-7*DAY,path:'boundary miss'},5);
add({type:'search_no_results',at:now-7*DAY-1,path:'expired miss'},6);
add({type:'purchase',at:now-DAY},7);
add({type:'checkout_start',at:now-DAY+1},8);
add({type:'add_to_cart',at:now-30*DAY,path:'first item',title:'First',qty:2},9);
add({type:'add_to_cart',at:now-29*DAY,path:'second item',title:'Second',qty:3},10);
add({type:'register_interest',at:now-30*DAY,path:'display',title:'Display',qty:1},11);
