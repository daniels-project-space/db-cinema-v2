const assert = require('node:assert/strict');
const { load, db, put, tables, setMock } = require('./lib/rentalTestHarness.cjs');
process.env.ADMIN_TOKEN = 'fixture-admin';
process.env.STRIPE_SECRET_KEY = 'sk_test_fixture';
process.env.MEMBERSHIP_HISTORICAL_INVOICE_CREDIT_V1 = 'enabled';
let failNotes = false;
let issuedNote = false;
const invoice = { id:'in_fixture', status:'paid', amount_paid:1900, billing_reason:'subscription_cycle', currency:'gbp', livemode:false, customer:'cus_fixture', parent:{subscription_details:{subscription:'sub_fixture'}} };
const line = { id:'il_fixture', amount:1900, currency:'gbp', parent:{type:'subscription_item_details',subscription_item_details:{subscription:'sub_fixture',subscription_item:'si_old',proration:false}}, pricing:{price_details:{price:'price_fixture'}}, period:{start:1800000000,end:1802592000}, discount_amounts:[] };
const sub = { id:'sub_fixture', customer:'cus_fixture', metadata:{accountEmail:'fixture@example.invalid'}, items:{data:[]} };
setMock('stripe', { default: class { constructor() {
  this.accounts={retrieve:async()=>({id:'acct_fixture'})};
  this.invoices={listLineItems:async function*(){yield line;}};
  this.creditNotes={list:async function*(){if(failNotes)throw Error('synthetic outage');if(issuedNote)yield {id:'cn_fixture',status:'issued'};},listLineItems:async function*(){yield {invoice_line_item:'il_fixture',amount:950};yield {invoice_line_item:'il_unrelated',amount:500};}};
} } });
const review=load('convex/membershipInvoiceReviews.ts'), admin=load('convex/accountAdmin.ts'), benefits=load('convex/membershipBenefits.ts'), checkout=load('convex/checkout.ts');
const account=put('accounts',{email:'fixture@example.invalid',stripeCustomerId:'cus_fixture',stripeSubscriptionId:'sub_fixture',membershipTier:'studio'});
const ctx={db,scheduler:{runAfter:async()=>{}},runQuery:async(ref,args)=>{
  if(ref==='accounts._byEmail')return args.email===account.email?account:null;
  if(ref==='accountAdmin.membershipInvoiceReceipt')return admin.membershipInvoiceReceipt.handler(ctx,args);
  if(ref==='membershipInvoiceReviews.mayProcess')return review.mayProcess.handler(ctx,args);
  throw Error(`Unexpected query ${ref}`);
},runMutation:async(ref,args)=>{
  if(ref==='membershipInvoiceReviews.record')return review.record.handler(ctx,args);
  if(ref==='membershipInvoiceReviews.resolve')return review.resolve.handler(ctx,args);
  if(ref==='membershipBenefits.grantPaidInvoice')return benefits.grantPaidInvoice.handler(ctx,args);
  if(ref==='membershipBenefits.revokeRefundedInvoice')return benefits.revokeRefundedInvoice.handler(ctx,args);
  throw Error(`Unexpected mutation ${ref}`);
}};
(async()=>{
  delete process.env.MEMBERSHIP_INVOICE_PRICE_SNAPSHOTS;
  await checkout.grantStripeMembershipInvoice(ctx,invoice,sub);
  assert.equal((tables.get('membership_credit_grants')??[]).length,0);
  assert.equal((tables.get('membership_invoice_reviews')??[])[0].reason,'snapshot_not_configured');
  process.env.MEMBERSHIP_INVOICE_PRICE_SNAPSHOTS=JSON.stringify([{priceId:'price_fixture',stripeAccountId:'acct_fixture',livemode:false,tier:'plus',bonusPercent:10,termsVersion:'fixture'}]);
  await checkout.grantStripeMembershipInvoice(ctx,invoice,sub);
  assert.equal((tables.get('membership_credit_grants')??[]).length,0,'ambiguous reviews do not retry forever');
  failNotes=true;
  await checkout.grantStripeMembershipInvoice(ctx,invoice,sub,'fixture-admin');
  assert.equal((tables.get('membership_credit_grants')??[]).length,0,'provider failure cannot issue unreconciled credit');
  assert.equal(tables.get('membership_invoice_reviews')[0].state,'review','provider failure remains open for review');
  failNotes=false;
  issuedNote=true;
  await checkout.grantStripeMembershipInvoice(ctx,invoice,sub);
  assert.equal(tables.get('membership_credit_grants')[0].earnedCreditPence,2090,'old Plus invoice is not inflated by current Studio tier');
  assert.equal(tables.get('membership_credit_grants')[0].revokedPence,1045,'the grant mutation atomically applies existing credit notes');
  assert.equal(tables.get('credits')[0].remaining,10.45,'pre-existing refunded credit is never exposed as spendable');
  assert.equal(tables.get('membership_credit_grants').length,1,'retry cannot mint a second grant');
  assert.equal(tables.get('membership_invoice_reviews')[0].state,'resolved');
  failNotes=true;
  await checkout.grantStripeMembershipInvoice(ctx,invoice,sub);
  assert.equal(tables.get('membership_invoice_reviews')[0].state,'review','later reconciliation failures reopen');
  assert.equal(tables.get('admin_notifications').length,2,'reopened reconciliation sends a new owner alert');
  failNotes=false;
  await checkout.grantStripeMembershipInvoice(ctx,invoice,sub);
  assert.equal(tables.get('membership_credit_grants')[0].membershipRefundedPence,950,'a credit note matches the historical line even after its subscription item was removed');
  assert.equal(tables.get('membership_credit_grants')[0].revokedPence,1045,'refund uses the historical bonus, not the current plan');
  await checkout.grantStripeMembershipInvoice(ctx,invoice,sub);
  assert.equal(tables.get('membership_credit_grants')[0].revokedPence,1045,'replayed credit notes do not reverse credit twice');
  console.log('PASS gated membership invoice: ambiguity, bounded retry, historical tier, idempotent receipt and reconciliation recovery; synthetic Stripe only.');
})().catch(error=>{console.error(error);process.exitCode=1});
