const assert = require('node:assert/strict');
const { load, db, put } = require('./lib/rentalTestHarness.cjs');
const accounts = load('convex/accounts.ts');
const { bookingSteps } = load('src/lib/bookingDisplay.ts');
(async () => {
 const account = put('accounts', { email: 'renter@example.invalid' });
 put('sessions', { token: 'renter-test', accountId: account._id, expiresAt: Date.now() + 60000 });
 const unit = put('inventory_units', { name: 'DJI Mini 4 Pro' });
 const listing = put('listings', { title: 'Location kit with drone', components: [{ inventoryUnitId: unit._id }], category: 'Packages' });
 const booking = put('bookings', { guestEmail: account.email, accountId: account._id, status: 'confirmed', idVerifyStatus: 'verified', droneLicenceStatus: 'review', droneLicenceStorageId: 'private-document', lineItems: [{ listingId: listing._id, title: listing.title, start: 1, end: 2, qty: 1, lineTotal: 100 }], total: 100, depositAmount: 40.5, depositHoldAmount: 81, depositHoldStatus: 'held' });
 const [row] = await accounts.myBookings.handler({ db }, { token: 'renter-test' });
 assert.equal(row.requiresDroneLicence, true, 'Nested drone components must reach the renter account projection');
 assert.equal(row.droneLicenceStatus, 'review');
 assert.equal(JSON.stringify(row).includes('private-document'), false, 'Licence storage IDs never enter the account card projection');
 const current = b => bookingSteps(b).steps.find(s => s.state === 'current')?.label;
 assert.equal(current(row), 'Drone licence review');
 assert.equal(current({ ...row, droneLicenceStatus: 'requires_input' }), 'Replace drone licence');
 assert.equal(current({ ...row, droneLicenceStatus: 'required' }), 'Upload drone licence');
 assert.equal(current({ ...row, droneLicenceStatus: 'approved' }), 'Pickup');
 assert.equal(current({ ...row, depositHoldStatus: 'pending' }), 'Card hold');
 assert.equal(current({ ...row, idVerifyStatus: 'requires_input' }), 'Resubmission needed');
 assert.equal(current({ ...row, requiresDroneLicence: false }), 'Pickup');
 assert.equal(current({ ...row, status: 'active' }), 'Return');
 assert.equal(bookingSteps({ ...row, status: 'returned' }).steps.every(s => s.state === 'done'), true);
 assert.equal(bookingSteps({ ...row, status: 'cancelled' }).cancelled, true);
 assert.equal(current({ ...row, status: 'pending_payment' }), 'Payment');
 await db.patch(listing._id, { components: [], itemType: 'drone' });
 assert.equal((await accounts.myBookings.handler({ db }, { token: 'renter-test' }))[0].requiresDroneLicence, true);
 assert.equal(await accounts.myBookings.handler({ db }, { token: 'invalid' }), null);
 console.log('PASS actual renter account projection and progress: direct/nested drones, private-file exclusion, manual review/replacement/approval, unpaid/hold/document priorities and closed rentals.');
})().catch(e => { console.error(e); process.exitCode = 1; });
