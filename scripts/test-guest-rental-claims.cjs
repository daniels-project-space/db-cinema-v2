const scheduled = [];
const ctx = {db, scheduler:{runAfter:async(delay,ref,args)=>scheduled.push({ref,args})}};
const now = Date.now();
const account = put("accounts", {email:"verified@example.invalid", emailVerifiedAt:now-1000, hash:"hash", salt:"salt"});
const booking = put("bookings", {guestEmail:account.email,status:"active"});
const thread = put("chat_threads", {bookingId:booking._id,accountId:account._id,escalated:false});
const message = put("messages", {bookingId:booking._id,accountId:account._id,text:"Existing conversation"});
const pending = put("bookings", {guestEmail:account.email,status:"pending_verification",checkoutPaidAt:now});
const returned = put("bookings", {guestEmail:account.email,status:"returned"});
const cancelled = put("bookings", {guestEmail:account.email,status:"cancelled",checkoutPaidAt:now});
const unpaidCancelled = put("bookings", {guestEmail:account.email,status:"cancelled"});
const unpaid = put("bookings", {guestEmail:account.email,status:"pending_verification"});
const otherAccount = put("accounts", {email:"other@example.invalid",emailVerifiedAt:now-1000});
const foreignThread = put("bookings", {guestEmail:account.email,status:"active"});
put("chat_threads", {bookingId:foreignThread._id,accountId:otherAccount._id,escalated:false});
const alreadyLinked = put("bookings", {guestEmail:account.email,status:"active",accountId:otherAccount._id});
async function run(accountId) { const target=await db.get(accountId);const job=put("guest_rental_claim_jobs",{accountId,expectedEmail:target.email,state:"pending",cursor:null,attempts:1,generation:1,nextAttemptAt:now,conflicts:0,updatedAt:now});await claims.claimVerifiedPage.handler(ctx,{jobId:job._id,generation:1});return job; }
function queuedFor(accountId) {return (tables.get("guest_rental_claim_jobs")??[]).some(job=>job.accountId===accountId);}
(async()=>{
  const reviewJob=await run(account._id);
  assert.equal(booking.accountId,account._id); assert.equal(pending.accountId,account._id);
  assert.equal(returned.accountId,account._id);assert.equal(cancelled.accountId,account._id);assert.equal(unpaidCancelled.accountId,undefined);
  assert.equal(thread.accountId,account._id); assert.equal(message.accountId,account._id);
  assert.equal(unpaid.accountId,undefined); assert.equal(foreignThread.accountId,undefined); assert.equal(alreadyLinked.accountId,otherAccount._id);
  assert.equal(reviewJob.state,"review");
  await assert.rejects(claims.reviewStatus.handler(ctx,{token:"bad",accountId:account._id}),/unauthorized/);
  await assert.rejects(claims.retryReview.handler(ctx,{token:"bad",accountId:account._id}),/unauthorized/);
  const previousGeneration=reviewJob.generation;
  await claims.retryReview.handler(ctx,{token:"fixture-admin",accountId:account._id});
  assert.equal(reviewJob.state,"pending");assert(reviewJob.generation>previousGeneration);
  await claims.claimVerifiedPage.handler(ctx,{jobId:reviewJob._id,generation:previousGeneration});
  assert.equal(foreignThread.accountId,undefined,"stale generation cannot claim another renter’s thread");
  const unverified = put("accounts", {email:"unverified@example.invalid"});
  const unverifiedBooking = put("bookings", {guestEmail:unverified.email,status:"active"});
  put("sessions",{accountId:unverified._id,token:"unverified-legacy",expiresAt:now+60000});
  await run(unverified._id); assert.equal(unverifiedBooking.accountId,undefined);
  assert.equal(rentalAccount.belongsToRentalAccount(unverifiedBooking,unverified),false);
  await assert.rejects(rentalChat.ownedBooking(ctx,unverified,unverifiedBooking._id),/not available/);
  assert.equal((await rentalAccount.rentalsForAccount(ctx,unverified,50)).length,0);
  assert.equal(await firstEligibleRentalConfirmationAt(ctx,unverified),undefined,"an unverified guest-email match cannot unlock membership benefits");
  const unverifiedChat=await rentalChatApi.minePage.handler(ctx,{token:"unverified-legacy",paginationOpts:{cursor:null,numItems:20}});
  assert.deepEqual(unverifiedChat.page,[],"chat history never exposes the unverified legacy match");
  const reviewCandidate={guestEmail:unverified.email,status:"returned",pickedUpAt:now-1000,actualReturnedAt:now,idVerifyStatus:"verified",paidConfirmedAt:now-1000,total:100,stripePaymentIntentId:"pi_synthetic",lineItems:[{title:"Private equipment",start:now-2000,end:now-1000,qty:1,lineTotal:100}]};
  const unverifiedReviewBooking=put("bookings",reviewCandidate);
  const foreignReviewBooking=put("bookings",{...reviewCandidate,accountId:otherAccount._id});
  put("review_prize_entries",{accountId:unverified._id,bookingId:foreignReviewBooking._id});
  const hiddenReviews=await reviewPrize.mine.handler(ctx,{token:"unverified-legacy"});
  assert.deepEqual(hiddenReviews.bookings,[],"review prize discovery does not leak unverified or foreign rentals");
  assert.deepEqual(hiddenReviews.entries,[],"a stale entry cannot expose a reassigned rental");
  assert.equal(unverifiedReviewBooking.accountId,undefined);
  const cancellationContext={runQuery:async(ref)=>ref==="accounts._byToken"?unverified:ref==="bookings.getForCancel"?unverifiedBooking:null};
  await assert.rejects(checkout.cancelUnpaidByCustomer.handler(cancellationContext,{token:"unverified-legacy",bookingId:unverifiedBooking._id}),/unauthorized/);
  unverified.emailVerifiedAt=now;
  await assert.rejects(checkout.cancelUnpaidByCustomer.handler(cancellationContext,{token:"unverified-legacy",bookingId:unverifiedBooking._id}),/Only unpaid direct checkout/,"a verified legacy renter reaches the normal cancellation gate");
  delete unverified.emailVerifiedAt;
  const linkedUnverified=put("bookings",{accountId:unverified._id,guestEmail:unverified.email,status:"active"});
  assert.equal(rentalAccount.belongsToRentalAccount(linkedUnverified,unverified),true,"the verified-email requirement applies only to unlinked legacy rentals");
  assert((await rentalAccount.rentalsForAccount(ctx,unverified,50)).some(row=>row._id===linkedUnverified._id));
  const verifiedLegacy=put("bookings",{guestEmail:account.email,status:"returned"});
  assert.equal(await rentalChat.ownedBooking(ctx,account,verifiedLegacy._id),verifiedLegacy,"verified legacy ownership still works");
  const paged=put("accounts",{email:"paged@example.invalid",emailVerifiedAt:now});
  const pagedBookings=Array.from({length:23},()=>put("bookings",{guestEmail:paged.email,status:"returned"}));
  const pagedJob=put("guest_rental_claim_jobs",{accountId:paged._id,expectedEmail:paged.email,state:"pending",cursor:null,attempts:1,generation:1,nextAttemptAt:now,conflicts:0,updatedAt:now});
  await claims.claimVerifiedPage.handler(ctx,{jobId:pagedJob._id,generation:1});
  assert.equal(pagedJob.state,"pending");assert.equal(pagedBookings.filter(item=>item.accountId===paged._id).length,10);
  await claims.claimVerifiedPage.handler(ctx,{jobId:pagedJob._id,generation:1});
  await claims.claimVerifiedPage.handler(ctx,{jobId:pagedJob._id,generation:1});
  assert.equal(pagedJob.state,"done");assert.equal(pagedBookings.filter(item=>item.accountId===paged._id).length,23,"pagination does not lose entries when claimed rows leave the index");
  const blocked = put("accounts", {email:"blocked@example.invalid",emailVerifiedAt:now,blockedAt:now});
  const blockedBooking = put("bookings", {guestEmail:blocked.email,status:"active"});
  await run(blocked._id); assert.equal(blockedBooking.accountId,undefined);
  const duplicate = put("accounts", {email:"duplicate@example.invalid",emailVerifiedAt:now});
  put("accounts", {email:duplicate.email,emailVerifiedAt:now});
  const ambiguous = put("bookings", {guestEmail:duplicate.email,status:"active"});
  await run(duplicate._id); assert.equal(ambiguous.accountId,undefined);
  const changed=put("accounts",{email:"new@example.invalid",emailVerifiedAt:now});
  const changedJob=put("guest_rental_claim_jobs",{accountId:changed._id,expectedEmail:"old@example.invalid",state:"pending",cursor:"old-cursor",attempts:1,generation:1,nextAttemptAt:now,conflicts:0,updatedAt:now});
  await claims.claimVerifiedPage.handler(ctx,{jobId:changedJob._id,generation:1});
  assert.equal(changedJob.state,"review","a changed email cannot resume an old cursor");
  const exhausted=put("guest_rental_claim_jobs",{accountId:otherAccount._id,expectedEmail:otherAccount.email,state:"pending",cursor:null,attempts:5,generation:7,nextAttemptAt:now-1,conflicts:0,updatedAt:now});
  await claims.dispatchDue.handler(ctx,{});
  assert.equal(exhausted.state,"review","repeated failures stop retrying and require review");
  assert((tables.get("admin_notifications")??[]).some(notice=>notice.accountId===otherAccount._id&&notice.title.includes("needs review")),"exhausted retries notify the team");
  const passwordAccount=put("accounts",{email:"password@example.invalid",emailVerifiedAt:now,hash:"hash",salt:"salt"});
  await accounts._session.handler(ctx,{accountId:passwordAccount._id,token:"password-session",expectedPasswordHash:"hash"});
  assert(queuedFor(passwordAccount._id),"verified password login schedules claim");
  const emailAccount=put("accounts",{email:"magic@example.invalid",emailVerificationRequired:true});
  put("account_access_links",{accountId:emailAccount._id,secretHash:"secret",expiresAt:now+60000});
  await access.exchange.handler(ctx,{secretHash:"secret",sessionToken:"magic-session"});
  assert(queuedFor(emailAccount._id),"email link verification schedules claim");
  const guestAccount=put("accounts",{email:"guest-link@example.invalid",emailVerificationRequired:true});
  const guestBooking=put("bookings",{guestEmail:guestAccount.email,status:"active"});
  put("account_access_links",{accountId:guestAccount._id,bookingId:guestBooking._id,secretHash:"booking-secret",expiresAt:now+60000});
  const exchange=await access.exchange.handler(ctx,{secretHash:"booking-secret",sessionToken:"guest-session"});
  assert.equal(exchange.bookingId,guestBooking._id,"a booking-bound one-time link can establish email verification before a legacy claim");
  assert(guestAccount.emailVerifiedAt && queuedFor(guestAccount._id));
  const foreignLink=put("account_access_links",{accountId:guestAccount._id,bookingId:alreadyLinked._id,secretHash:"foreign-booking-secret",expiresAt:now+60000});
  await assert.rejects(access.exchange.handler(ctx,{secretHash:"foreign-booking-secret",sessionToken:"bad-session"}),/no longer valid/);
  assert.equal(foreignLink.usedAt,undefined,"a link cannot claim another account's linked rental");
  const codeAccount=put("accounts",{email:"code@example.invalid"});
  put("account_codes",{email:codeAccount.email,purpose:"reset",setupHash:"setup",verifiedAt:now,expiresAt:now+60000});
  await codes.finish.handler(ctx,{setupHash:"setup",salt:"salt",hash:"hash",sessionToken:"code-session"});
  assert(queuedFor(codeAccount._id),"verified code completion schedules claim");
  const googleAccount=put("accounts",{email:"google@example.invalid",googleId:"google-id",emailVerifiedAt:now});
  await google._upsertGoogle.handler(ctx,{email:googleAccount.email,googleId:"google-id",token:"google-session"});
  assert(queuedFor(googleAccount._id),"Google sign-in schedules claim");
  console.log("PASS verified guest booking claim, ownership guards, existing chat and authentication entry points");
})().catch(error=>{console.error(error);process.exitCode=1});
