const assert = require("node:assert/strict");
process.env.ADMIN_TOKEN="fixture-admin";
const {load, db, put, tables} = require("./lib/rentalTestHarness.cjs");
const claims = load("convex/guestRentalClaims.ts");
const accounts = load("convex/accounts.ts");
const access = load("convex/accountClaims.ts");
const codes = load("convex/accountCodeClaims.ts");
const google = load("convex/googleAuth.ts");
const rentalAccount = load("convex/lib/rentalAccount.ts");
const rentalChat = load("convex/lib/rentalChat.ts");
const rentalChatApi = load("convex/rentalChat.ts");
const reviewPrize = load("convex/reviewPrize.ts");
const checkout = load("convex/checkout.ts");
