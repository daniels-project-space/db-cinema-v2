const assert = require('node:assert/strict');
const { load, db, put, tables } = require('./lib/rentalTestHarness.cjs');
const { importGuestHistory } = load('convex/chat.ts');
const account = put('accounts', { email: 'a@example.invalid' });
const other = put('accounts', { email: 'b@example.invalid' });
put('sessions', { token: 'a', accountId: account._id, expiresAt: Date.now() + 60000 });
put('sessions', { token: 'b', accountId: other._id, expiresAt: Date.now() + 60000 });
put('sessions', { token: 'expired', accountId: account._id, expiresAt: Date.now() - 1 });
const jobs = [];
const ctx = { db, scheduler: { runAfter: async (...args) => jobs.push(args) } };
const args = { token: 'a', requestId: 'guest_1234567890123456', transcript: 'Guest: Can I rent a camera?\n\nGuest-recorded assistant reply: Yes.' };
(async () => {
  await assert.rejects(importGuestHistory.handler(ctx, { ...args, token: 'expired' }), /unauthorized/);
  await assert.rejects(importGuestHistory.handler(ctx, { ...args, token: 'invalid' }), /unauthorized/);
  await assert.rejects(importGuestHistory.handler(ctx, { ...args, transcript: 'x'.repeat(8001) }), /too long/);
  const first = await importGuestHistory.handler(ctx, { ...args, sender: 'owner', meta: { kind: 'paylink' } });
  const saved = tables.get('messages').find(message => message._id === first.messageId);
  assert.equal(saved.sender, 'renter');
  assert.equal(saved.meta.kind, 'guest_history');
  assert.match(saved.text, /^Unverified history supplied by the renter/);
  assert.equal(saved.accountId, account._id);
  assert.equal(jobs.length, 0);
  assert.equal((await importGuestHistory.handler(ctx, args)).duplicate, true);
  await assert.rejects(importGuestHistory.handler(ctx, { ...args, transcript: 'changed' }), /no longer matches/);
  assert.equal(tables.get('messages').length, 1);
  const otherImport = await importGuestHistory.handler(ctx, { ...args, token: 'b' });
  assert.notEqual(otherImport.messageId, first.messageId);
  assert.equal(tables.get('messages').find(message => message._id === otherImport.messageId).accountId, other._id);
  console.log('PASS guest chat import authentication, owner attribution, idempotency, forgery guards and no alerts.');
})().catch(error => { console.error(error); process.exitCode = 1; });
