const assert = require('node:assert/strict');
const {load, db, put, tables, setMock} = require('./lib/rentalTestHarness.cjs');
process.env.ADMIN_TOKEN = 'fixture-admin';
delete process.env.RMV2_WEBHOOK_URL;
let sends = 0, transportFails = false;
const sentMessages = [];
setMock('./lib/mailer', {sendBusinessMail: async message => { sends++; sentMessages.push(message); if (transportFails) throw Error('Simulated uncertain delivery'); return true; }});
const admin = load('convex/accountAdmin.ts');
const notices = load('convex/accountRestrictionNotice.ts');
const mail = load('convex/accountRestrictionMail.ts');
const scheduled = [];
let mutationTail = Promise.resolve();
const ctx = {db, scheduler: {runAfter: async (_delay, ref, args) => scheduled.push({ref, args})},
  runMutation: (ref, args) => {
    const result = mutationTail.then(() => notices[ref.split('.')[1]].handler(ctx, args));
    mutationTail = result.catch(() => {});
    return result;
  }};
const account = put('accounts', {email: 'renter@example.invalid', emailVerifiedAt: 1, createdAt: 1});
const expected = value => ({blockedAt:value.blockedAt ?? null, restrictionClass:value.restrictionClass??null, noticeId:value.restrictionNoticeId ?? null, reason:value.blockedReason ?? '',revision:value.restrictionRevision ?? 0});
const restrictionReason = 'Identity & <review> "needs follow-up"\nPlease reply.';
const block = (blocked, restrictionClass=account.restrictionClass??'access_only') => admin.setBlocked.handler(ctx, {token: 'fixture-admin', accountId: account._id, blocked, restrictionClass, reason: restrictionReason, expected:expected(account)});
(async () => {
  await assert.rejects(admin.setBlocked.handler(ctx, {token: 'bad', accountId: account._id, blocked: true, restrictionClass:'identity_safety_blacklist', reason: 'reason'}));
  await block(true,'identity_safety_blacklist');
  assert.equal(account.restrictionClass,'identity_safety_blacklist','The explicit safety class is stored on the account');
  assert.equal(tables.get('account_admin_changes').find(row=>row.accountId===account._id&&row.kind==='block')?.after,'blocked · identity_safety_blacklist','The exact classification is recorded in admin history');
  const first = tables.get('account_restriction_notices')[0];
  assert.equal(first.reason, restrictionReason, 'The notice snapshots the bounded reason entered with this restriction');
  await block(true);
  assert.equal(tables.get('account_restriction_notices').length, 1);
  await notices.dispatchOne.handler(ctx, {noticeId: first._id});
  assert.equal(first.state, 'sending');
  await Promise.all([mail.deliver.handler(ctx, {noticeId: first._id}), mail.deliver.handler(ctx, {noticeId: first._id})]);
  assert.equal(sends, 1, 'Duplicate action execution must not send twice');
  assert.equal(first.state, 'sent');
  assert.match(sentMessages[0].html, /Identity &amp; &lt;review&gt; &quot;needs follow-up&quot;<br>Please reply\./, 'Customer-provided reason text is escaped before insertion into HTML');
  assert.equal(sentMessages[0].html.includes('<review>'), false, 'Reason text cannot inject HTML into the notification');
  assert(sentMessages[0].text.includes(`Reason provided to our team:\n${restrictionReason}`), 'The email also includes a readable plain-text reason');
  assert.match(sentMessages[0].html, /Access to your DB Cinema account has been restricted/, 'The identity/safety class still receives the standard renter restriction notice');
  const detail = await admin.detail.handler(ctx, {token:'fixture-admin',accountId:account._id});
  assert.equal(detail.restrictionNotice.state, 'sent');
  assert.equal('recipient' in detail.restrictionNotice, false, 'The notice projection does not expose the stored recipient');
  await assert.rejects(admin.detail.handler(ctx, {token:'bad',accountId:account._id}), /unauthorized/);
  const safetyBlockedAt=account.blockedAt,safetyNoticeId=account.restrictionNoticeId,safetyNoticeCount=tables.get('account_restriction_notices').length,safetyEmailCount=sends;
  await admin.setBlocked.handler(ctx,{token:'fixture-admin',accountId:account._id,blocked:true,restrictionClass:'access_only',reason:'Classified as access-only after review',expected:expected(account)});
  assert.equal(account.blockedAt,safetyBlockedAt,'Reclassification keeps the original blockedAt');
  assert.equal(account.restrictionNoticeId,safetyNoticeId,'Reclassification keeps the current notice binding');
  assert.equal(tables.get('account_restriction_notices').length,safetyNoticeCount,'Reclassification does not create a new notice');
  assert.equal(sends,safetyEmailCount,'Reclassification does not email the renter a second time');
  assert.equal(tables.get('account_admin_changes').at(-1).kind,'restriction_reclassify');
  const accessOnly = put('accounts', {email:'access-only@example.invalid',emailVerifiedAt:1,createdAt:1});
  await admin.setBlocked.handler(ctx,{token:'fixture-admin',accountId:accessOnly._id,blocked:true,restrictionClass:'access_only',reason:'Access-only fixture restriction',expected:expected(accessOnly)});
  assert.equal(accessOnly.restrictionClass,'access_only');
  assert.equal(tables.get('account_admin_changes').find(row=>row.accountId===accessOnly._id&&row.kind==='block')?.after,'blocked · access_only');
  const accessNotice=tables.get('account_restriction_notices').find(row=>row.accountId===accessOnly._id);
  await notices.dispatchOne.handler(ctx,{noticeId:accessNotice._id});
  await mail.deliver.handler(ctx,{noticeId:accessNotice._id});
  assert.equal(accessNotice.state,'sent');
  assert.match(sentMessages[1].html,/Access to your DB Cinema account has been restricted/,'An access-only restriction also sends the renter notice');
  await block(false); await block(true);
  const stale = tables.get('account_restriction_notices')[2];
  await block(false); await block(true);
  await notices.dispatchOne.handler(ctx, {noticeId: stale._id});
  assert.equal(stale.state, 'skipped', 'An old restriction cannot send after it is replaced');
  const unverified = put('accounts', {email: 'unverified@example.invalid', createdAt: 1});
  await admin.setBlocked.handler(ctx, {token:'fixture-admin', accountId:unverified._id, blocked:true, restrictionClass:'access_only', reason:'reason', expected:expected(unverified)});
  assert.equal(unverified.restrictionClass,'access_only');
  const unsafe = tables.get('account_restriction_notices').at(-1);
  await notices.dispatchOne.handler(ctx, {noticeId:unsafe._id});
  assert.equal(unsafe.state, 'attention');
  assert((tables.get('admin_notifications') ?? []).some(row => row.accountId === unverified._id));
  const pending = tables.get('account_restriction_notices')[3];
  await db.patch(pending._id, {dueAt: 0});
  await notices.dispatchOne.handler(ctx, {noticeId:pending._id});
  assert.equal(pending.state, 'sending', 'The first dispatch must claim the notice before simulating an uncertain attempt');
  await db.patch(pending._id, {dueAt: 0});
  await notices.dispatchOne.handler(ctx, {noticeId:pending._id});
  assert.equal(pending.state, 'attention', 'An ambiguous transport attempt is never automatically repeated');
  const uncertainAccount = put('accounts', {email:'uncertain@example.invalid',emailVerifiedAt:1,createdAt:1});
  await admin.setBlocked.handler(ctx, {token:'fixture-admin',accountId:uncertainAccount._id,blocked:true,restrictionClass:'identity_safety_blacklist',reason:restrictionReason,expected:expected(uncertainAccount)});
  assert.equal(uncertainAccount.restrictionClass,'identity_safety_blacklist');
  const uncertain = tables.get('account_restriction_notices').at(-1);
  await notices.dispatchOne.handler(ctx, {noticeId:uncertain._id});
  transportFails = true;
  await mail.deliver.handler(ctx, {noticeId:uncertain._id});
  const afterUncertain = sends;
  assert.equal(uncertain.state, 'attention');
  await mail.deliver.handler(ctx, {noticeId:uncertain._id});
  assert.equal(sends, afterUncertain, 'An uncertain provider result is never automatically sent again');
  console.log('PASS simulated serialized restriction notices: authorization, reason snapshot and HTML escaping, plain text, verified recipient, replay/idempotency, stale prevention and email failure.');
})().catch(error => { console.error(error); process.exitCode=1; });
