const assert=require('node:assert/strict');
const {load,db,put}=require('./lib/rentalTestHarness.cjs');
const {calculateRentalPrice}=load('convex/lib/rentalPrice.ts');
const catalog=load('convex/catalog.ts');
const benefits=load('convex/membershipBenefits.ts');
const bookings=load('convex/bookings.ts');
const {londonMonth}=load('convex/lib/memberDelivery.ts');
(async()=>{
 const acct=put('accounts',{email:'pricing@example.invalid',membershipActive:true,membershipTier:'pro',membershipStatus:'active',membershipPaidThrough:Date.now()+86400000});
 const camera=put('listings',{active:true,title:'Camera',pricing:{daily:200},depositAmount:2000,quietDeal:5,itemType:'camera'});
 let london=true;
 const ctx={db,scheduler:{runAfter:async()=>{}},runQuery:async(ref,args)=>{
  if(ref==='accounts._byToken')return args.token==='real' ? acct:null;
  if(ref==='catalog.repriceLines')return catalog.repriceLines.handler({db},args);
  if(ref==='membershipBenefits.deliveryAvailable')return benefits.deliveryAvailable.handler({db},args);
  if(ref==='bookings.availableCheckoutCredit')return 0;
  if(ref==='promo.validate')return {valid:true,discount:50,code:'STACK'};
  throw Error('unexpected query '+ref);
 },runAction:async(ref,args)=>{assert.equal(ref,'delivery.quote');return{ok:true,fee:100,isLondon:london};}};
 const input={items:[{listingId:camera._id,title:'tampered',start:Date.UTC(2027,0,1),end:Date.UTC(2027,0,3),qty:1,total:1,deposit:1}],token:'real',customer:{email:acct.email},fulfilment:'delivery',address:'25 Whitcomb Street London WC2H 7ER',deliveryPostcode:'WC2H7ER',promoCode:'STACK'};
 let price=await calculateRentalPrice(ctx,input);
 assert.equal(price.subtotal,540,'weekend starts with regular 3-day rate, no quiet deal');
 assert.equal(price.totalReduction,100,'aggregate saving capped, promo does not stack');
 assert.equal(price.appliedCode,undefined);
 assert.equal(price.deliveryFee,70);
 assert.equal(price.depositAmount,0);
 assert.ok(price.depositHoldAmount>0,'waiver preserves full hold');
 camera.quietDeal=50;price=await calculateRentalPrice(ctx,input);assert.equal(price.weekendSaving,0,'a weekend deal never increases a cheaper ordinary quote');assert.equal(price.totalReduction,50);camera.quietDeal=5;
 acct.membershipTier='plus';price=await calculateRentalPrice(ctx,input);
 assert.equal(price.subtotal,513,'ordinary quiet discount remains without weekend deal');
 assert.equal(price.totalReduction,50);assert.equal(price.deliveryFee,90);
 acct.membershipTier='studio';price=await calculateRentalPrice(ctx,input);
 assert.equal(price.deliveryFee,0);assert.equal(price.deliveryBenefitMonth,londonMonth());
 const args={customerEmail:acct.email,fulfilment:'delivery',address:input.address,deliveryFee:0,lineItems:price.items.map(i=>({listingId:i.listingId,title:i.title,start:i.start,end:i.end,qty:i.qty,lineTotal:i.total})),subtotal:price.subtotal,depositAmount:price.depositAmount,depositHoldAmount:price.depositHoldAmount,discount:price.totalReduction,total:price.totalBeforeCredit,expectedTotalDue:price.totalDue,creditAccountId:acct._id,deliveryBenefitMonth:price.deliveryBenefitMonth,securityWaiverReason:price.securityWaiverReason,currency:'GBP'};
 const created=await bookings.createPending.handler(ctx,args);
 await assert.rejects(bookings.createPending.handler(ctx,args),/already been reserved/);
 price=await calculateRentalPrice(ctx,input);assert.equal(price.deliveryFee,100,'pending booking reserves monthly quota');
 await db.patch(created.bookingId,{status:'cancelled'});
 price=await calculateRentalPrice(ctx,input);assert.equal(price.deliveryFee,0,'cancel before handover releases quota');
 await db.patch(created.bookingId,{deliveryBenefitConsumed:true});
 price=await calculateRentalPrice(ctx,input);assert.equal(price.deliveryFee,100,'delivered/canceled rental cannot reclaim used allowance');
 london=false;await db.patch(created.bookingId,{deliveryBenefitConsumed:false});
 price=await calculateRentalPrice(ctx,input);assert.equal(price.deliveryFee,100,'London-only entitlement');
 acct.membershipStatus='trialing';price=await calculateRentalPrice(ctx,input);assert.ok(price.depositAmount>0,'free week keeps security payment');
 await assert.rejects(calculateRentalPrice(ctx,{...input,customer:{email:'somebodyelse@example.invalid'}}),/signed-in account email/);
 price=await calculateRentalPrice(ctx,{...input,token:'forged'});assert.ok(price.depositAmount>0);assert.equal(price.totalReduction,50);assert.equal(price.deliveryFee,100);
 // Public recommendation endpoint uses the same clock-based entitlement as its prices.
 const checkout=load('convex/checkout.ts');
 acct.stripeSubscriptionId='sub_expired';acct.membershipStatus='active';acct.membershipTier='pro';acct.membershipPaidThrough=Date.now()-1000;
 const quoteArgs={...input,customer:undefined,customerEmail:acct.email};delete quoteArgs.customer;
 const expired=await checkout.priceQuote.handler(ctx,quoteArgs);
 assert.equal(expired.recommendations.length,3,'expired membership must not hide the subscription offer');
 acct.membershipPaidThrough=Date.now()+86400000;
 const active=await checkout.priceQuote.handler(ctx,quoteArgs);
 assert.equal(active.recommendations.length,0,'current members do not get a duplicate subscription upsell');
 console.log('Member rental pricing: real catalog repricing, weekend cap/nonstack, trial hold, delivery tiers and atomic monthly quota passed.');
})().catch(e=>{console.error(e);process.exitCode=1;});
