const assert = require("node:assert/strict");
const { load, db, put, setMock } = require("./lib/rentalTestHarness.cjs");
process.env.ADMIN_TOKEN = "fixture-admin";
process.env.SHARED_STOCK_BRIDGE_EXPERIMENTAL = "true";
let enabled = false;
setMock("./lib/rentalSwapAuthority", { swapAuthorityAvailable: () => enabled });
setMock("./lib/rentalAllocation", { assertRentalAllocation: async () => {} });
const audit = load("convex/swapStockAudit.ts");
const ctx = { db, scheduler: { runAfter: async () => {} } };
const unit = put("inventory_units", { rmv2ItemId: "manager-item" });
const booking = put("bookings", { status: "confirmed", rmv2Revision: 2 });
const swap = put("rental_item_swaps", { bookingId: booking._id, status: "applied", stockAppliedAt: 100, oldLine: { title: "Camera" }, newLine: { title: "Lens" } });
const reservation = put("reservations", { bookingId: booking._id, inventoryUnitId: unit._id, source: "site", status: "confirmed", start: 1000, end: 2000, qty: 1, endExclusive: true, turnaroundBufferMinutes: 60 });
const receipt = put("swap_stock_applied_receipts", { bookingId: booking._id, swapId: swap._id, bookingRevision: 1, appliedAt: 100, managerRequestId: "claim", fingerprint: "fingerprint", executionKey: `swap_execution_${swap._id}`, windows: [{ reservationId: reservation._id, inventoryUnitId: unit._id, managerItemId: unit.rmv2ItemId, start: reservation.start, end: reservation.end, quantity: 1, endExclusive: true, turnaroundBufferMinutes: 60 }] });
put("swap_stock_operations", { swapId: swap._id, operation: "acquire", state: "confirmed", receipt: { requestId: "claim", fingerprint: "fingerprint" } });
const execution = put("swap_stock_operations", { swapId: swap._id, operation: "beginExecution", state: "confirmed", request: { args: { id: "claim", fingerprint: "fingerprint", executionKey: receipt.executionKey } } });
const args = { token: "fixture-admin", bookingId: booking._id, id: receipt._id, confirmed: true };
(async () => {
  await assert.rejects(audit.retryLegacyDelivery.handler(ctx, { ...args, token: "wrong" }), /unauthorized/);
  await assert.rejects(audit.retryLegacyDelivery.handler(ctx, args), /not enabled/);
  enabled = true;
  await assert.rejects(audit.retryLegacyDelivery.handler(ctx, { ...args, confirmed: false }), /Confirm/);
  await assert.rejects(audit.retryLegacyDelivery.handler(ctx, { ...args, bookingId: "bookings-other" }), /individual stock review/);
  booking.rmv2SyncLeaseUntil = Date.now() + 10000;
  await assert.rejects(audit.retryLegacyDelivery.handler(ctx, args), /delivery needs individual review/);
  booking.rmv2SyncLeaseUntil = undefined;
  reservation.qty = 2;
  await assert.rejects(audit.retryLegacyDelivery.handler(ctx, args), /allocation or delivery needs individual review/);
  reservation.qty = 1;
  execution.request.args.executionKey = "changed";
  await assert.rejects(audit.retryLegacyDelivery.handler(ctx, args), /execution is not confirmed/);
  execution.request.args.executionKey = receipt.executionKey;
  assert.equal((await audit.conflicts.handler(ctx, { token: args.token, bookingId: booking._id }))[0].legacy, true);
  assert.deepEqual(await audit.retryLegacyDelivery.handler(ctx, args), { status: "pending" });
  assert.equal(receipt.deliveryState, "pending");
  assert.equal(booking.activeItemSwapId, swap._id);
  assert.equal(booking.rmv2Revision, 3);
  await assert.rejects(audit.retryLegacyDelivery.handler(ctx, args), /individual stock review/);
  console.log("PASS legacy receipt review: authorization, gate, changed evidence, active delivery lease and duplicate retry; synthetic data only.");
})().catch(error => { console.error(error); process.exitCode = 1; });
