const assert = require('node:assert/strict');
const {load, db, put, docs, tables} = require('./lib/rentalTestHarness.cjs');
process.env.ADMIN_TOKEN = 'fixture-admin';
const admin = load('convex/accountAdmin.ts'), accounts = load('convex/accounts.ts');
const google = load('convex/googleAuth.ts'), claims = load('convex/accountClaims.ts');
const {membershipActiveNow, membershipTierFor, paidDepositExempt} = load('shared/membership.ts');
const {calculateRentalPrice} = load('convex/lib/rentalPrice.ts');
const {fundEntryPence} = load('shared/filmFund.ts');
const bookings = load('convex/bookings.ts'), catalog = load('convex/catalog.ts');
const ctx = {db, scheduler:{runAfter:async()=>{}}, runQuery:async(ref,args)=>{
  if(ref==='accounts._byEmail')return accounts._byEmail.handler(ctx,args);
  if(ref==='accounts._byToken')return accounts._byToken.handler(ctx,args);
  if(ref==='catalog.repriceLines')return catalog.repriceLines.handler(ctx,args);
  if(ref==='bookings.availableCheckoutCredit')return bookings.availableCheckoutCredit.handler(ctx,args);
  throw Error('Unexpected query '+ref);
}};
const account = put('accounts',{email:'person@example.invalid',name:'QA Renter',salt:'private-salt',hash:'private-hash',createdAt:1});
const session = put('sessions',{accountId:account._id,token:'person-session',expiresAt:Date.now()+3600000});
const emailLink = put('account_access_links',{accountId:account._id,secretHash:'private-link',createdAt:1,expiresAt:Date.now()+3600000});
const change = (level,token='fixture-admin')=>admin.setLevel.handler(ctx,{token,accountId:account._id,level,reason:'QA access change'});
const block = blocked=>admin.setBlocked.handler(ctx,{token:'fixture-admin',accountId:account._id,blocked,reason:'QA access change'});
(async()=>{
  assert.deepEqual((await admin.search.handler(ctx,{token:'wrong',email:''})).items,[]);
  await assert.rejects(change('studio','wrong'),/unauthorized/);
  assert.equal(account.adminMembershipTier,undefined);
  const found = await admin.search.handler(ctx,{token:'fixture-admin',email:' PERSON@'});
  assert.equal(found.items.length,1);
  for(const secret of ['salt','hash','address','stripeSubscriptionId'])assert.equal(secret in found.items[0],false,'Search must not leak private fields');
  assert.deepEqual(await admin.history.handler(ctx,{token:'wrong',accountId:account._id}),[]);
  await assert.rejects(admin.setLevel.handler(ctx,{token:'fixture-admin',accountId:account._id,level:'pro',reason:' '}),/reason/);
  for(const level of ['plus','pro','studio']) {
    await change(level);assert.equal(membershipTierFor(account),level);assert.equal(membershipActiveNow(account),true);
    assert.equal(paidDepositExempt(account),false,'A complimentary grant cannot invent paid deposit entitlement');
    assert.equal((await accounts.me.handler(ctx,{token:session.token})).membershipTier,level);
  }
  assert.equal((tables.get('credits')??[]).length,0,'Promotion does not mint credit');
  await change('plus');assert.equal(fundEntryPence(account),1500,'Starter grant uses Starter fund pricing');
  await change('standard');assert.equal(membershipActiveNow(account),false);assert.equal(membershipTierFor(account),undefined);
  await change('automatic');assert.equal(account.adminMembershipTier,undefined);assert.equal(membershipActiveNow(account),false);
  Object.assign(account,{membershipTier:'plus',membershipActive:true,membershipStatus:'active',membershipPaidThrough:Date.now()+86400000,stripeSubscriptionId:'sub-fixture'});
  await change('studio');assert.equal(account.membershipTier,'plus','Underlying paid plan is preserved');
  const invoice = load('convex/membershipBenefits.ts');
  await invoice.grantPaidInvoice.handler(ctx,{accountId:account._id,subscriptionId:'sub-fixture',invoiceId:'invoice-qa',paidMembershipPence:1900,periodEnd:Date.now()+86400000});
  assert.equal((tables.get('credits')??[]).reduce((sum,c)=>sum+c.amount,0),20.9,'Owner promotion cannot inflate paid invoice credit');
  await accounts._applyMembershipReconcile.handler(ctx,{accountId:account._id,active:false,tier:'plus'});
  assert.equal(membershipTierFor(account),'studio','Provider reconciliation cannot erase owner access');
  await change('standard');assert.equal(paidDepositExempt(account),false);
  await change('automatic');assert.equal(membershipTierFor(account),'plus');
  const camera=put('listings',{active:true,title:'QA Camera',pricing:{daily:200},depositAmount:1000});
  const input={items:[{listingId:camera._id,title:camera.title,start:Date.UTC(2027,0,8),end:Date.UTC(2027,0,9),qty:1,total:1,deposit:1}],customer:{email:account.email},token:session.token,fulfilment:'pickup',protection:'verify'};
  await change('pro');const price=await calculateRentalPrice(ctx,input);assert.equal(price.weekendSaving,100,'Promotion reaches real rental pricing');
  await change('standard');assert.equal((await calculateRentalPrice(ctx,input)).weekendSaving,0,'Demotion removes the actual weekend benefit');
  const rental=put('bookings',{guestEmail:account.email,status:'confirmed',total:100});
  const balance=(tables.get('credits')??[]).map(c=>({...c}));
  await block(true);assert.equal(docs.has(session._id),false);assert.equal(docs.has(emailLink._id),false);
  assert.equal(await accounts.me.handler(ctx,{token:session.token}),null);
  assert.equal(await accounts._authFor.handler(ctx,{token:session.token}),null);
  await assert.rejects(accounts._session.handler(ctx,{accountId:account._id,token:'replacement'}),/blocked/);
  await assert.rejects(accounts.signIn.handler(ctx,{email:account.email,password:'anything'}),/blocked/);
  await assert.rejects(google._upsertGoogle.handler(ctx,{email:account.email,googleId:'qa-google',token:'google-session'}),/blocked/);
  assert.equal(await claims.prepareSignIn.handler(ctx,{email:account.email,secretHash:'new-link'}),null);
  put('account_access_links',{accountId:account._id,secretHash:'stale-link',createdAt:1,expiresAt:Date.now()+3600000});
  await assert.rejects(claims.exchange.handler(ctx,{secretHash:'stale-link',sessionToken:'email-session'}),/blocked/);
  await assert.rejects(calculateRentalPrice(ctx,{...input,token:undefined}),/blocked/,'Signing out cannot bypass the email booking block');
  await assert.rejects(bookings.createPending.handler(ctx,{customerEmail:account.email,fulfilment:'pickup',deliveryFee:0,lineItems:[],subtotal:0,depositAmount:0,discount:0,total:0,currency:'GBP'}),/blocked/);
  assert.equal(rental.status,'confirmed','Block preserves owner-manageable rentals');
  assert.deepEqual(tables.get('credits'),balance,'Block never erases balances');
  await block(false);assert.equal(account.blockedAt,undefined);
  assert.equal(await accounts.me.handler(ctx,{token:session.token}),null,'Unblocking never revives revoked sessions');
  await accounts._session.handler(ctx,{accountId:account._id,token:'new-session'});
  assert(await accounts.me.handler(ctx,{token:'new-session'}),'A new sign-in works after unblocking');
  for(let i=0;i<60;i++)put('accounts',{email:`other${i}@example.invalid`,createdAt:1});
  const bounded=await admin.search.handler(ctx,{token:'fixture-admin',email:'other'});assert.equal(bounded.items.length,50);assert.equal(bounded.more,true);
  assert((await admin.history.handler(ctx,{token:'fixture-admin',accountId:account._id})).length>0,'Changes retain an account audit history');
  console.log('PASS admin accounts: authorized/private email search, level overrides, real rental perks, unchanged billing/credit, password/Google/email/session/guest-booking blocks, revocation, unblocking and audit history.');
})().catch(e=>{console.error(e);process.exitCode=1});
