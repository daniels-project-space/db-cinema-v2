const assert = require('node:assert/strict');
const { load, put, db } = require('./lib/rentalTestHarness.cjs');
process.env.ADMIN_TOKEN = 'catalog-revision-fixture';
const catalog = load('convex/catalog.ts');
const admin = load('convex/marketingAdmin.ts');
const sync = load('convex/sync.ts');
const ctx = { db };

(async () => {
  const row = put('listings', { title: 'Sony FX3 Camera', slug: 'fx3', category: 'Cameras', itemType: 'camera-body', active: true, marketingOnly: false, marketingOnlySource: 'admin', components: [], pricing: { daily: 50 }, depositAmount: 0 });
  assert.equal(await catalog.publicRevision.handler(ctx, {}), 'v2:0');
  await assert.rejects(admin.save.handler(ctx, { token: 'wrong', changes: [{ listingId: row._id, marketingOnly: true }] }), /unauthorized/);
  assert.equal(await catalog.publicRevision.handler(ctx, {}), 'v2:0');
  await admin.save.handler(ctx, { token: process.env.ADMIN_TOKEN, changes: [{ listingId: row._id, marketingOnly: true }] });
  assert.equal(await catalog.publicRevision.handler(ctx, {}), 'v2:1');
  assert(!(await catalog.listListings.handler(ctx, {})).some(item => item._id === row._id), 'Marketing-only items disappear from the public projection');
  const managed = put('listings', { ...row, _id: 'listings-managed-revision', hyggloProductId: 55, marketingOnly: true, marketingOnlySource: 'rental_manager', marketingOnlyMode: 'manual', marketingOnlyUpdatedAt: 10 });
  const change = { productId: 55, marketingOnly: false, mode: 'manual', updatedAt: 11 };
  await sync.applyManagerMarketingTags.handler(ctx, { changes: [change] });
  assert.equal(managed.marketingOnly, false);
  assert.equal(await catalog.publicRevision.handler(ctx, {}), 'v2:2');
  await sync.applyManagerMarketingTags.handler(ctx, { changes: [change] });
  await sync.applyManagerMarketingTags.handler(ctx, { changes: [{ ...change, marketingOnly: true, updatedAt: 10 }] });
  assert.equal(await catalog.publicRevision.handler(ctx, {}), 'v2:2', 'Duplicate and stale pushes do not churn cache versions');
  await sync.suppressByIds.handler(ctx, { ids: [row._id], suppressed: true });
  assert.equal(await catalog.publicRevision.handler(ctx, {}), 'v2:3', 'Suppression invalidates cached discovery');
  await sync.suppressByIds.handler(ctx, { ids: [], suppressed: false });
  assert.equal(await catalog.publicRevision.handler(ctx, {}), 'v2:3');
  await sync.setItemTypes.handler(ctx, { updates: [{ id: row._id, itemType: 'accessory' }] });
  assert.equal(await catalog.publicRevision.handler(ctx, {}), 'v2:4', 'Classification changes invalidate cached discovery');
  row.quietDeal = 10;
  await catalog.refreshQuietDeals.handler(ctx, {});
  assert.equal(await catalog.publicRevision.handler(ctx, {}), 'v2:5', 'Changed discounts invalidate cached featured prices');
  await catalog.applyR2Images.handler(ctx, { token: process.env.ADMIN_TOKEN, items: [{ slug: 'fx3', r2Images: ['https://example.com/new-image.jpg'] }] });
  assert.equal(await catalog.publicRevision.handler(ctx, {}), 'v2:6', 'Changed catalogue images invalidate cached featured cards');
  console.log('PASS catalogue revision: protected writes, live manager toggle, idempotency and policy generation');
})().catch(error => { console.error(error); process.exitCode = 1; });
