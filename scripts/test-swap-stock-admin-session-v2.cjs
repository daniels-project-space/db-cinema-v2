const assert = require('node:assert/strict');
const { createHash, webcrypto } = require('node:crypto');
const { load, db, put, setMock } = require('./lib/rentalTestHarness.cjs');
global.crypto ??= webcrypto;
const sessions = load('convex/adminSessionsV2.ts');
const identityAuth = load('convex/adminAccountSessionV2.ts');
let ready = false;
setMock('./adminAccountSessionV2', { ...identityAuth, adminSessionMigrationReady: () => ready });
setMock('./lib/rentalSwapAuthority', { swapAuthorityAvailable: () => true });
const audit = load('convex/swapStockAudit.ts');
const identity = 'https://identity.example|stock-admin', token = 'a'.repeat(64), readToken = 'b'.repeat(64);
const hash = value => createHash('sha256').update(value).digest('hex');
const ctx = { db, auth: { getUserIdentity: async () => ({ tokenIdentifier: identity }) }, scheduler: { runAfter: async () => {} } };
const booking = put('bookings', {}), swap = put('rental_item_swaps', { oldLine: { title: 'Camera' }, newLine: { title: 'Lens' } });
const receipt = put('swap_stock_applied_receipts', { bookingId: booking._id, swapId: swap._id, stockRisk: true, deliveryState: 'acknowledged' });
(async () => {
  process.env.ADMIN_TOKEN = 'legacy-stock-fixture';
  process.env.ADMIN_SESSION_SWAP_STOCK_V2 = 'enabled';
  process.env.ADMIN_SESSION_SCOPES_V2 = JSON.stringify({ [identity]: ['rentals:read', 'rentals:write'] });
  await sessions.createSession.handler(ctx, { tokenDigest: hash(token), principalId: `admin:${hash(identity)}`, scopes: ['rentals:read', 'rentals:write'], expiresAt: Date.now() + 60000 });
  await sessions.createSession.handler(ctx, { tokenDigest: hash(readToken), principalId: `admin:${hash(identity)}`, scopes: ['rentals:read'], expiresAt: Date.now() + 60000 });
  const read = { token, bookingId: booking._id }, manual = { bookingId: booking._id, id: receipt._id, adminToken: token };
  await assert.rejects(audit.conflicts.handler(ctx, read), /not ready/);
  await assert.rejects(audit.retryLegacyDelivery.handler(ctx, { ...read, id: receipt._id, confirmed: true }), /not ready/);
  ready = true;
  await assert.rejects(audit.conflicts.handler(ctx, { ...read, token: process.env.ADMIN_TOKEN }), /unauthorized/);
  assert.equal((await audit.conflicts.handler(ctx, read)).length, 1);
  await assert.rejects(audit.prepareManualCheck.handler(ctx, { ...manual, adminToken: readToken }), /unauthorized/);
  await audit.prepareManualCheck.handler(ctx, manual);
  assert.equal((await audit.manualCheckResult.handler(ctx, manual)).status, 'review');
  process.env.SHARED_STOCK_BRIDGE_EXPERIMENTAL = 'true';
  ctx.runMutation = async (ref, args) => {
    if (ref === 'swapStockAudit.prepareManualCheck') return audit.prepareManualCheck.handler(ctx, args);
    if (ref === 'swapStockAudit.claim') return { operation: 'checkConversion', args: {} };
    if (ref === 'swapStockAudit.record') return audit.record.handler(ctx, args);
    throw Error(`Unexpected mutation ${ref}`);
  };
  ctx.runAction = async () => { await sessions.revoke.handler(ctx, { tokenDigest: hash(token) }); return { status: 'confirmed', result: { stockRisk: false } }; };
  ctx.runQuery = async (ref, args) => audit.manualCheckResult.handler(ctx, args);
  await assert.rejects(audit.recheck.handler(ctx, { ...read, id: receipt._id }), /unauthorized/, 'Revocation during the external check prevents applying the result');
  assert.equal(receipt.stockRisk, true);
  await assert.rejects(audit.claim.handler(ctx, { id: receipt._id, token: 'lease', adminToken: token }), /unauthorized/);
  await assert.rejects(audit.record.handler(ctx, { id: receipt._id, token: 'lease', adminToken: token, result: {} }), /unauthorized/);
  await assert.rejects(audit.manualCheckResult.handler(ctx, manual), /unauthorized/);
  delete process.env.ADMIN_SESSION_SWAP_STOCK_V2;
  assert.equal((await audit.conflicts.handler(ctx, { ...read, token: process.env.ADMIN_TOKEN })).length, 1);
  console.log('PASS staged stock-review access: readiness, scoped reads/writes, revoked sessions and legacy compatibility; synthetic data only.');
})().catch(error => { console.error(error); process.exitCode = 1; });
