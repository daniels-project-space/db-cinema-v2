const assert=require('node:assert/strict');
const {load}=require('./lib/rentalTestHarness.cjs');
const {rentalChatReminderPlan}=load('shared/rentalChatReminders.ts');
const {londonRentalInstant}=load('shared/rentalWindow.ts');
const day=(year,month,date)=>Date.UTC(year,month-1,date);
const pickup=londonRentalInstant(day(2030,6,1),'10:00'),returned=londonRentalInstant(day(2030,6,3),'18:00');
const line={listingId:'camera',title:'Camera',qty:1,start:day(2030,6,1),end:day(2030,6,3),pickupTime:'10:00',returnTime:'18:00'};
const second={...line,listingId:'lens',title:'Lens'};
const different={...line,listingId:'light',title:'Light',end:day(2030,6,4),returnTime:'19:00'};
const events=rentalChatReminderPlan({lineItems:[line,second,different]});
assert.equal(events.filter(event=>event.kind==='pickup').length,1);
assert.equal(events.find(event=>event.kind==='pickup').dueAt,pickup-3600000);
assert.equal(events.filter(event=>event.kind==='return').length,2);
assert.equal(events.find(event=>event.kind==='return'&&event.eventAt===returned).dueAt,returned-3600000);
assert.equal(events.filter(event=>event.kind==='halfway').length,1);
const lastReturn=londonRentalInstant(day(2030,6,4),'19:00');
assert(events.some(event=>event.kind==='halfway'&&event.dueAt===pickup+Math.floor((lastReturn-pickup)/2)));
assert.deepEqual(events.map(event=>event.key).sort(),rentalChatReminderPlan({lineItems:[different,second,line]}).map(event=>event.key).sort(),'item reorder does not create a new reminder');
assert.notDeepEqual(events.map(event=>event.key).sort(),rentalChatReminderPlan({lineItems:[{...line,returnTime:'17:00'},second,different]}).map(event=>event.key).sort(),'reschedules invalidate old snapshots');
assert.deepEqual(rentalChatReminderPlan({lineItems:[{...line,pickupTime:null}]}),[],'unknown time never gets guessed');
assert.deepEqual(rentalChatReminderPlan({lineItems:[{...line,start:day(2030,3,31),pickupTime:'01:30'}]}),[],'nonexistent London wall times are rejected');
assert.equal(londonRentalInstant(day(2030,6,1),'10:00'),Date.UTC(2030,5,1,9),'summer London clock is converted to BST');
console.log('PASS chat reminder planning: exact London instants, split item windows, stable snapshots, changes and invalid times.');
