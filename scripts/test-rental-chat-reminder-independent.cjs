const assert = require('node:assert/strict');
const {load,db,put,tables} = require('./lib/rentalTestHarness.cjs');
const reminders = load('convex/rentalChatReminders.ts');
const {londonRentalInstant} = load('shared/rentalWindow.ts');
const jobs=[];
const ctx={db,scheduler:{runAfter:async(delay,ref,args)=>{jobs.push({delay,ref,args});return `job-${jobs.length}`;}}};
const day=Date.UTC(2032,5,1), pickup=londonRentalInstant(day,'10:00'), originalNow=Date.now;
let clock=pickup-7200000;
Date.now=()=>clock;
const account=put('accounts',{email:'verified@example.invalid',emailVerifiedAt:clock-10000});
const base={accountId:account._id,guestEmail:account.email,status:'confirmed',fulfilment:'pickup',paidConfirmedAt:clock-10000,verificationProvider:'didit',idVerificationSource:'didit',idVerifyStatus:'verified',idVerifiedAt:clock-10000,verificationChecks:{identity:'approved',selfie:'approved',address:'approved'},lineItems:[{listingId:'camera',title:'Private camera',qty:1,start:day,end:day+86400000,pickupTime:'10:00',returnTime:'18:00'}]};
const rows=()=>tables.get('rental_chat_reminders')??[];
const messages=()=>tables.get('messages')??[];

(async()=>{try{
  const legacyAccount=put('accounts',{email:'legacy@example.invalid'});
  const legacy=put('bookings',{...base,_id:'legacy-rental',accountId:undefined,guestEmail:legacyAccount.email});
  await reminders.scheduleRentalChatReminders(ctx,legacy);
  const legacyRow=rows().find(row=>row.bookingId===legacy._id&&row.kind==='pickup');
  clock=pickup-3600000;
  if(legacyRow)await reminders.deliver.handler(ctx,{reminderId:legacyRow._id});
  assert.equal(messages().some(message=>message.bookingId===legacy._id),false,'matching an unverified legacy email never receives private booking details');
  const unverified=put('accounts',{email:'unverified@example.invalid'});
  const linked=put('bookings',{...base,_id:'unverified-mail-rental',accountId:unverified._id,guestEmail:unverified.email});
  clock=pickup-7200000;await reminders.scheduleRentalChatReminders(ctx,linked);
  const unverifiedRow=rows().find(row=>row.bookingId===linked._id&&row.kind==='pickup');
  clock=pickup-3600000;if(unverifiedRow)await reminders.deliver.handler(ctx,{reminderId:unverifiedRow._id});
  assert.equal(messages().some(message=>message.bookingId===linked._id),false,'unverified mailbox receives no booking reminder');
  const rental=put('bookings',{...base,_id:'rescheduled-rental',lineItems:base.lineItems.map(line=>({...line}))});
  clock=pickup-7200000;await reminders.scheduleRentalChatReminders(ctx,rental);
  const original=rows().find(row=>row.bookingId===rental._id&&row.kind==='pickup');
  await db.patch(rental._id,{lineItems:rental.lineItems.map(line=>({...line,pickupTime:'11:00'}))});
  await reminders.scheduleRentalChatReminders(ctx,rental);
  await db.patch(rental._id,{lineItems:rental.lineItems.map(line=>({...line,pickupTime:'10:00'}))});
  await reminders.scheduleRentalChatReminders(ctx,rental);
  clock=original.dueAt;await reminders.deliver.handler(ctx,{reminderId:original._id});
  await reminders.deliver.handler(ctx,{reminderId:original._id});
  assert.equal(messages().filter(message=>message.bookingId===rental._id).length,1,'A→B→A sends the original occurrence exactly once');
  const gap=put('bookings',{...base,_id:'staggered-gap-rental',status:'active',pickedUpAt:pickup,
    lineItems:[{...base.lineItems[0],end:day,returnTime:'12:00'}, {...base.lineItems[0],listingId:'later-lens',title:'Later lens',start:day+2*86400000,end:day+2*86400000,returnTime:'12:00'}]});
  clock=pickup-7200000;await reminders.scheduleRentalChatReminders(ctx,gap);
  const midpoint=rows().find(row=>row.bookingId===gap._id&&row.kind==='halfway');
  assert(midpoint,'staggered rental has a planned midpoint');clock=midpoint.dueAt;
  await reminders.deliver.handler(ctx,{reminderId:midpoint._id});
  const gapMessages=messages().filter(message=>message.bookingId===gap._id);
  assert.equal(gapMessages.length,1,'a rental receives its midpoint check-in even between separate item windows');
  assert.doesNotMatch(gapMessages[0].text,/Items:|currently out/i,'the midpoint does not imply any particular kit is currently out');
  const cancelled=put('bookings',{...base,_id:'cancelled-after-rental'});
  clock=pickup-7200000;await reminders.scheduleRentalChatReminders(ctx,cancelled);
  const cancelledRow=rows().find(row=>row.bookingId===cancelled._id&&row.kind==='pickup');
  await db.patch(cancelled._id,{status:'cancelled'});clock=pickup-3600000;
  if(cancelledRow)await reminders.deliver.handler(ctx,{reminderId:cancelledRow._id});
  assert.equal(messages().some(message=>message.bookingId===cancelled._id),false,'a cancelled booking cannot send previously scheduled reminders');
  const neverVerified=put('bookings',{...base,_id:'never-verified-rental',status:'pending_verification',idVerifyStatus:'rejected',idVerifiedAt:undefined});
  clock=pickup-7200000;await reminders.scheduleRentalChatReminders(ctx,neverVerified);
  await db.patch(neverVerified._id,{status:'returned',returnedAt:pickup});
  await reminders.scheduleRentalChatReminders(ctx,neverVerified);
  assert.equal(rows().some(row=>row.bookingId===neverVerified._id),false,'a paid but never-verified rental remains ineligible even after being marked returned');
  console.log('PASS independent reminder review: mailbox ownership, A→B→A replay and post-schedule cancellation.');
}finally{Date.now=originalNow;}})().catch(error=>{console.error(error);process.exitCode=1;});
